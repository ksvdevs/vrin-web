import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { loadEnvFile } from 'node:process';

const envFile = new URL('../.env', import.meta.url);
if (existsSync(envFile)) {
  // Variables supplied by the deployment environment take precedence.
  loadEnvFile(envFile);
}

const target = new URL('../src/environments/license.generated.ts', import.meta.url);
const license = process.env.PRIMEUI_LICENSE_KEY ?? '';
const content = '// Generated by scripts/generate-env.mjs. Do not edit.\n'
  + `export const primeuiLicenseKey = ${JSON.stringify(license)};\n`;

mkdirSync(new URL('../src/environments/', import.meta.url), { recursive: true });
if (!existsSync(target) || readFileSync(target, 'utf8') !== content) {
  writeFileSync(target, content, 'utf8');
}
